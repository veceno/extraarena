#!/usr/bin/env python3
"""Build a balanced canonical Nemesis preview from audited V5 self-play.

The two authoritative legacy corpora were generated by
``generate_aux_synthetic_v1.py``.  Their raw battle IDs overlap and their
``candidate_*`` deck fields are relative to ``candidate_seat`` rather than to
the physical p1/p2 seats.  This converter:

* accepts only complete, terminal, non-truncated, error-free battles;
* preserves complete four-battle seed quartets (both seats x both starters);
* contributes the same number of quartets from every checkpoint campaign;
* maps candidate/opponent decks to p1/p2 exactly;
* namespaces battle IDs by campaign and checkpoint;
* writes the canonical ``extraarena_nemesis_battle_v1`` export format;
* writes leakage-safe matchup groups to a training-metadata sidecar.

Legacy requested levels for ``simplified_levelup`` cards are normalized to
their effective engine level.  The source generator passed levels up to 10,
while ``core.card_scaling.scale_card_by_level`` clamped those cards to level 2
before the initial game state was created.  Keeping the requested value would
misdescribe the battle and is rejected by the current Nemesis loader.
"""
