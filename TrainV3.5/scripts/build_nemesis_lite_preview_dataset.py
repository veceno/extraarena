def _main_checkout_root() -> Path:
    try:
        common = subprocess.check_output(
            [
                "git",
                "-C",
                str(REPO_ROOT),
                "rev-parse",
                "--path-format=absolute",
                "--git-common-dir",
            ],
            text=True,
        ).strip()
        return Path(common).resolve().parent
    except Exception:
        return REPO_ROOT


def default_source_specs() -> list[tuple[str, Path]]:
    training_root = (
        _main_checkout_root()
        / ".claude"
        / "worktrees"
        / "glm-TrainV3.5Prep"
        / "TrainV3.5"
        / "runs"
    )
    return [
        (
            "u29250-selfplay-20260723",
            training_root / "aux_synthetic_v1_u29250_10000_20260723_2247",
        ),
        (
            "h299-selfplay-20260727",
            training_root / "aux_authoritative_h299_dense20k_s7_20260727",
        ),
    ]


def _parse_source_specs(values: Sequence[str]) -> list[tuple[str, Path]]:
    if not values:
        return default_source_specs()
    result: list[tuple[str, Path]] = []
    for value in values:
        if "=" not in value:
            raise ValueError("--source must be CAMPAIGN_ID=PATH")
        campaign_id, raw_path = value.split("=", 1)
        result.append((_slug(campaign_id), Path(raw_path)))
    return result


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        action="append",
        default=[],
        metavar="CAMPAIGN_ID=PATH",
        help=(
            "Audited aux-synthetic campaign. Repeat for every checkpoint; "
            "defaults to the preserved u29250 and h299 campaigns."
        ),
    )
    parser.add_argument(
        "--catalog",
        type=Path,
        default=REPO_ROOT / "ai" / "cards.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=REPO_ROOT / "TrainV3.5" / "runs" / DEFAULT_OUTPUT_NAME,
    )
    parser.add_argument("--selection-seed", type=int, default=20260728)
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    catalog = load_catalog(args.catalog)
    source_specs = _parse_source_specs(args.source)
    campaigns = [
        load_campaign(campaign_id, path, catalog=catalog)
        for campaign_id, path in source_specs
    ]
    manifest = build_preview(
        campaigns,
        catalog=catalog,
        output_dir=args.output,
        selection_seed=args.selection_seed,
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
